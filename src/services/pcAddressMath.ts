export interface SavedPcAddress {
  id: string;
  address: string;
  displayHost: string;
  label: string;
  pairCode?: string;
  lastUsedAt: string;
}

export interface ParsedPcAddress {
  address: string;
  displayHost: string;
  pairCode?: string;
}

/**
 * Parses and normalizes user-entered PC addresses such as:
 * - "192.168.1.25:3000"
 * - "http://192.168.1.25:3000/?pair=482910&mode=mobile"
 * - "https://my-office-pc.example.com"
 * - "DESKTOP-OFFICE:3000"
 */
export function parsePcAddressInput(rawInput: string, fallbackCode?: string): ParsedPcAddress | null {
  const trimmed = rawInput.trim();
  if (!trimmed) return null;

  const hasProtocol = /^[a-zA-Z][a-zA-Z0-9+.-]*:\/\//.test(trimmed);
  const candidateUrl = hasProtocol ? trimmed : `http://${trimmed}`;

  try {
    const parsed = new URL(candidateUrl);
    if (!parsed.hostname) return null;

    const extractedPair = parsed.searchParams.get('pair')?.replace(/\D/g, '').slice(0, 6);
    const cleanedFallback = fallbackCode?.replace(/\D/g, '').slice(0, 6);
    const finalPair =
      extractedPair && extractedPair.length === 6
        ? extractedPair
        : cleanedFallback && cleanedFallback.length === 6
        ? cleanedFallback
        : undefined;

    const normalizedOrigin = `${parsed.protocol}//${parsed.host}`;
    return {
      address: normalizedOrigin,
      displayHost: parsed.host,
      pairCode: finalPair,
    };
  } catch {
    // Fallback for custom/hostnames URL parser might reject
    const cleanHost = trimmed.replace(/^https?:\/\//i, '').split('/')[0]?.trim();
    if (!cleanHost) return null;
    const cleanedFallback = fallbackCode?.replace(/\D/g, '').slice(0, 6);
    return {
      address: `http://${cleanHost}`,
      displayHost: cleanHost,
      pairCode: cleanedFallback && cleanedFallback.length === 6 ? cleanedFallback : undefined,
    };
  }
}

export function upsertSavedPcAddress(
  list: SavedPcAddress[],
  entry: {
    address: string;
    label?: string;
    pairCode?: string;
    nowIso?: string;
    idFactory?: () => string;
  }
): { nextList: SavedPcAddress[]; savedEntry: SavedPcAddress | null } {
  const parsed = parsePcAddressInput(entry.address, entry.pairCode);
  if (!parsed) {
    return { nextList: list, savedEntry: null };
  }

  const nowIso = entry.nowIso || new Date().toISOString();
  const existing = list.find((item) => item.address.toLowerCase() === parsed.address.toLowerCase());
  const nextLabel = entry.label?.trim() || existing?.label || parsed.displayHost;
  const nextPairCode = parsed.pairCode || existing?.pairCode;

  const savedEntry: SavedPcAddress = {
    id: existing?.id || (entry.idFactory ? entry.idFactory() : `pc_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`),
    address: parsed.address,
    displayHost: parsed.displayHost,
    label: nextLabel,
    pairCode: nextPairCode,
    lastUsedAt: nowIso,
  };

  const remaining = list.filter((item) => item.id !== savedEntry.id);
  return {
    nextList: [savedEntry, ...remaining],
    savedEntry,
  };
}

export function removeSavedPcAddress(list: SavedPcAddress[], id: string): SavedPcAddress[] {
  return list.filter((item) => item.id !== id);
}

export function toWebSocketUrl(originOrAddress: string): string {
  const parsed = parsePcAddressInput(originOrAddress);
  if (!parsed) return '';
  const wsProto = parsed.address.startsWith('https://') ? 'wss://' : 'ws://';
  return `${wsProto}${parsed.displayHost}/ws`;
}

export interface QrPairingPayload {
  address?: string;
  pairCode?: string;
  label?: string;
}

/**
 * Decodes QR payloads generated by Desktop Pairing, LAN URLs, JSON configs, or bare 6-digit codes:
 * - "http://192.168.1.25:3000/?pair=482910&mode=mobile"
 * - '{"address":"192.168.1.25:3000","pairCode":"482910","label":"Office PC"}'
 * - "oklivo://pair?host=192.168.1.25:3000&code=482910"
 * - "482910"
 */
export function parseQrPairingPayload(rawText: string): QrPairingPayload | null {
  const trimmed = rawText.trim();
  if (!trimmed) return null;

  // 1. Bare 6-digit pairing code
  if (/^\d{6}$/.test(trimmed)) {
    return { pairCode: trimmed };
  }

  // 2. JSON payload
  if (trimmed.startsWith('{') && trimmed.endsWith('}')) {
    try {
      const obj = JSON.parse(trimmed) as Record<string, unknown>;
      const rawAddr =
        (typeof obj.address === 'string' && obj.address) ||
        (typeof obj.url === 'string' && obj.url) ||
        (typeof obj.host === 'string' && obj.host) ||
        '';
      const rawCode =
        (typeof obj.pairCode === 'string' && obj.pairCode) ||
        (typeof obj.code === 'string' && obj.code) ||
        (typeof obj.pair === 'string' && obj.pair) ||
        (typeof obj.pairCode === 'number' && String(obj.pairCode)) ||
        (typeof obj.code === 'number' && String(obj.code)) ||
        '';
      const label = typeof obj.label === 'string' ? obj.label.trim() : undefined;

      const parsedAddr = rawAddr ? parsePcAddressInput(rawAddr, rawCode) : null;
      const cleanCode = (parsedAddr?.pairCode || rawCode).replace(/\D/g, '').slice(0, 6);
      if (parsedAddr || cleanCode.length === 6) {
        return {
          address: parsedAddr?.address,
          pairCode: cleanCode.length === 6 ? cleanCode : undefined,
          label: label || parsedAddr?.displayHost,
        };
      }
    } catch {
      // fall through to URL parsing
    }
  }

  // 3. URL / custom scheme query parameters (e.g. http://.../?pair=123456 or oklivo://pair?host=...&code=123456)
  if (trimmed.includes('://') || /^oklivo:/i.test(trimmed)) {
    try {
      const url = new URL(trimmed);
      const qCode = (url.searchParams.get('pair') || url.searchParams.get('code') || '')
        .replace(/\D/g, '')
        .slice(0, 6);
      const qHost = url.searchParams.get('host') || url.searchParams.get('address') || '';
      if (qHost) {
        const parsedHost = parsePcAddressInput(qHost, qCode);
        if (parsedHost) {
          return {
            address: parsedHost.address,
            pairCode: parsedHost.pairCode || (qCode.length === 6 ? qCode : undefined),
            label: parsedHost.displayHost,
          };
        }
      }
      if (/^https?:$/i.test(url.protocol)) {
        const parsedHttp = parsePcAddressInput(trimmed);
        if (parsedHttp) {
          return {
            address: parsedHttp.address,
            pairCode: parsedHttp.pairCode,
            label: parsedHttp.displayHost,
          };
        }
      }
      if (qCode.length === 6) {
        return { pairCode: qCode };
      }
    } catch {
      // fall through
    }
  }

  // 4. Bare IP/hostname (e.g. 192.168.1.25:3000) or "pair:482910"
  const pairPrefix = trimmed.match(/^(?:pair|code)\s*[:=]\s*(\d{6})$/i);
  if (pairPrefix) {
    return { pairCode: pairPrefix[1] };
  }

  const fallbackAddr = parsePcAddressInput(trimmed);
  if (fallbackAddr && (fallbackAddr.displayHost.includes('.') || fallbackAddr.displayHost.includes(':'))) {
    return {
      address: fallbackAddr.address,
      pairCode: fallbackAddr.pairCode,
      label: fallbackAddr.displayHost,
    };
  }

  return null;
}
